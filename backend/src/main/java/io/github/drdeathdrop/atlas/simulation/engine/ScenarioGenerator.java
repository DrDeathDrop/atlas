package io.github.drdeathdrop.atlas.simulation.engine;

import io.github.drdeathdrop.atlas.incident.IncidentCategory;
import io.github.drdeathdrop.atlas.incident.NewIncident;
import io.github.drdeathdrop.atlas.incident.Severity;
import io.github.drdeathdrop.atlas.simulation.Scenario;
import org.springframework.stereotype.Component;

import java.util.Arrays;
import java.util.List;
import java.util.SplittableRandom;

@Component
public class ScenarioGenerator {
    static final double KILOMETERS_PER_DEGREE_LATITUDE = 111.2;

    private record Weighted<T>(T value, int weight) {
    }

    private static final List<Weighted<Severity>> SEVERITIES = List.of(
            new Weighted<>(Severity.LOW, 20),
            new Weighted<>(Severity.MEDIUM, 40),
            new Weighted<>(Severity.HIGH, 30),
            new Weighted<>(Severity.CRITICAL, 10));

    public NewIncident generate(Scenario scenario, double latitude, double longitude, double radiusKm,
                                boolean relatedIncidents, long seed, int index) {
        SplittableRandom random = new SplittableRandom(seed * 31 + index);

        IncidentCategory picked = pick(categoriesOf(scenario), random);
        boolean mixed = relatedIncidents || scenario == Scenario.RANDOM;
        IncidentCategory category = mixed ? picked : mainCategory(scenario);
        Severity severity = pick(SEVERITIES, random);

        double distanceKm = radiusKm * Math.sqrt(random.nextDouble());
        double bearing = random.nextDouble() * 2 * Math.PI;
        double northKm = distanceKm * Math.cos(bearing);
        double eastKm = distanceKm * Math.sin(bearing);
        double kilometersPerDegreeLongitude =
                KILOMETERS_PER_DEGREE_LATITUDE * Math.max(0.01, Math.cos(Math.toRadians(latitude)));

        double incidentLatitude = clamp(latitude + northKm / KILOMETERS_PER_DEGREE_LATITUDE, -90, 90);
        double incidentLongitude = clamp(longitude + eastKm / kilometersPerDegreeLongitude, -180, 180);

        return new NewIncident(
                "Simulated " + readable(category) + " #" + (index + 1),
                "Generated by the " + readable(scenario.name()) + " scenario of the disaster simulator. "
                        + "This is not a real incident.",
                category,
                severity,
                round(incidentLatitude),
                round(incidentLongitude),
                peopleFor(severity, random));
    }

    static IncidentCategory mainCategory(Scenario scenario) {
        return categoriesOf(scenario).get(0).value();
    }

    static List<IncidentCategory> possibleCategories(Scenario scenario) {
        return categoriesOf(scenario).stream().map(Weighted::value).toList();
    }

    private static List<Weighted<IncidentCategory>> categoriesOf(Scenario scenario) {
        return switch (scenario) {
            case FLOOD -> List.of(
                    new Weighted<>(IncidentCategory.FLOOD, 60),
                    new Weighted<>(IncidentCategory.LANDSLIDE, 10),
                    new Weighted<>(IncidentCategory.POWER_OUTAGE, 10),
                    new Weighted<>(IncidentCategory.WATER_SUPPLY_FAILURE, 10),
                    new Weighted<>(IncidentCategory.ROAD_ACCIDENT, 10));
            case EARTHQUAKE -> List.of(
                    new Weighted<>(IncidentCategory.EARTHQUAKE, 20),
                    new Weighted<>(IncidentCategory.BUILDING_COLLAPSE, 35),
                    new Weighted<>(IncidentCategory.GAS_LEAK, 15),
                    new Weighted<>(IncidentCategory.STRUCTURE_FIRE, 10),
                    new Weighted<>(IncidentCategory.POWER_OUTAGE, 10),
                    new Weighted<>(IncidentCategory.MEDICAL_EMERGENCY, 10));
            case WILDFIRE -> List.of(
                    new Weighted<>(IncidentCategory.WILDFIRE, 65),
                    new Weighted<>(IncidentCategory.STRUCTURE_FIRE, 15),
                    new Weighted<>(IncidentCategory.MEDICAL_EMERGENCY, 10),
                    new Weighted<>(IncidentCategory.MISSING_PERSON, 10));
            case INDUSTRIAL_ACCIDENT -> List.of(
                    new Weighted<>(IncidentCategory.CHEMICAL_LEAK, 35),
                    new Weighted<>(IncidentCategory.EXPLOSION, 25),
                    new Weighted<>(IncidentCategory.STRUCTURE_FIRE, 20),
                    new Weighted<>(IncidentCategory.MEDICAL_EMERGENCY, 20));
            case SEVERE_STORM -> List.of(
                    new Weighted<>(IncidentCategory.SEVERE_WEATHER, 45),
                    new Weighted<>(IncidentCategory.POWER_OUTAGE, 20),
                    new Weighted<>(IncidentCategory.ROAD_ACCIDENT, 15),
                    new Weighted<>(IncidentCategory.FLOOD, 10),
                    new Weighted<>(IncidentCategory.BUILDING_COLLAPSE, 10));
            case RANDOM -> Arrays.stream(IncidentCategory.values())
                    .filter(category -> category != IncidentCategory.OTHER)
                    .map(category -> new Weighted<>(category, 1))
                    .toList();
        };
    }

    private static <T> T pick(List<Weighted<T>> options, SplittableRandom random) {
        int total = options.stream().mapToInt(Weighted::weight).sum();
        int roll = random.nextInt(total);
        for (Weighted<T> option : options) {
            roll -= option.weight();
            if (roll < 0) {
                return option.value();
            }
        }
        return options.get(options.size() - 1).value();
    }

    private static int peopleFor(Severity severity, SplittableRandom random) {
        return switch (severity) {
            case LOW -> random.nextInt(0, 10);
            case MEDIUM -> random.nextInt(5, 100);
            case HIGH -> random.nextInt(50, 1000);
            case CRITICAL -> random.nextInt(500, 10000);
        };
    }

    private static String readable(IncidentCategory category) {
        return readable(category.name());
    }

    private static String readable(String name) {
        return name.toLowerCase().replace('_', ' ');
    }

    private static double clamp(double value, double min, double max) {
        return Math.max(min, Math.min(max, value));
    }

    private static double round(double value) {
        return Math.round(value * 1_000_000) / 1_000_000.0;
    }
}
